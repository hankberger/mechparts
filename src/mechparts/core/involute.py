"""Involute spur gear tooth profile generated analytically from a standard rack.

The profile is what a straight-sided rack cutter (ISO 53 basic rack, sharp tip
corner) would cut: an exact involute flank joined to the trochoid traced by the
cutter's tip corner. For low tooth counts that trochoid undercuts the involute,
exactly as on a hobbed gear, so the result meshes correctly with any other gear
of the same module and pressure angle.

Angles are in radians. A tooth is centred on the +X axis. ``half_angle(rho)``
gives the angular half-thickness of the tooth at radius ``rho``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass


def inv(a: float) -> float:
    """Involute function inv(a) = tan(a) - a."""
    return math.tan(a) - a


@dataclass(frozen=True)
class SpurGearGeometry:
    module: float
    teeth: int
    pressure_angle_deg: float = 20.0
    addendum_coef: float = 1.0
    dedendum_coef: float = 1.25

    # Derived dimensions -------------------------------------------------
    @property
    def alpha(self) -> float:
        return math.radians(self.pressure_angle_deg)

    @property
    def pitch_radius(self) -> float:
        return self.module * self.teeth / 2

    @property
    def base_radius(self) -> float:
        return self.pitch_radius * math.cos(self.alpha)

    @property
    def tip_radius(self) -> float:
        return self.pitch_radius + self.addendum_coef * self.module

    @property
    def root_radius(self) -> float:
        return self.pitch_radius - self.dedendum_coef * self.module

    @property
    def circular_pitch(self) -> float:
        return math.pi * self.module

    @property
    def undercut(self) -> bool:
        """True when the rack tip cuts into the involute (z below ~17 at 20 deg)."""
        return self.dedendum_coef * self.module > self.pitch_radius * math.sin(self.alpha) ** 2

    # Profile ------------------------------------------------------------
    def involute_half_angle(self, rho: float) -> float:
        """Half-angle of the involute tooth at radius rho (rho >= base radius)."""
        rb = self.base_radius
        a_rho = math.acos(min(1.0, rb / rho))
        s_half = math.pi / (2 * self.teeth)  # half of tooth thickness angle at pitch
        return s_half + inv(self.alpha) - inv(a_rho)

    def trochoid_half_angle(self, rho: float) -> float:
        """Half-angle bound imposed by the rack cutter's tip corner at radius rho."""
        r = self.pitch_radius
        hf = self.dedendum_coef * self.module
        c = self.circular_pitch / 4 - hf * math.tan(self.alpha)
        y = r - hf
        rho = max(rho, y)
        phi = (math.sqrt(max(0.0, rho * rho - y * y)) - c) / r
        # Corner position in the gear frame (tooth space centred on +Y axis).
        x0 = c + r * phi
        px = x0 * math.cos(phi) - y * math.sin(phi)
        py = x0 * math.sin(phi) + y * math.cos(phi)
        ang = math.atan2(py, px)
        # Tooth to the right of that space is centred at pi/2 - pi/z.
        return ang - (math.pi / 2 - math.pi / self.teeth)

    def half_angle(self, rho: float) -> float:
        if rho < self.junction_radius():
            return self.trochoid_half_angle(rho)
        return self.involute_half_angle(rho)

    def junction_radius(self) -> float:
        """Radius where the root trochoid (fillet) hands over to the involute flank.

        Without undercut this is the form circle: the point generated by the end
        of the rack's straight flank, where fillet and involute meet tangentially.
        With undercut the tip-corner trochoid cuts into the involute, and the
        junction is where the two curves cross.
        """
        if not self.undercut:
            r, hf = self.pitch_radius, self.dedendum_coef * self.module
            return math.sqrt((r - hf) ** 2 + (hf / math.tan(self.alpha)) ** 2)
        return self._junction_cache()

    def _junction_cache(self) -> float:
        cached = self.__dict__.get("_junction")
        if cached is None:
            cached = self._undercut_crossing()
            object.__setattr__(self, "_junction", cached)
        return cached

    def _undercut_crossing(self) -> float:
        lo = max(self.base_radius, self.root_radius)
        hi = self.tip_radius
        f = lambda p: self.trochoid_half_angle(p) - self.involute_half_angle(p)  # noqa: E731
        n = 400
        prev_p, prev_f = lo, f(lo)
        if prev_f >= 0:
            return lo
        for i in range(1, n + 1):
            p = lo + (hi - lo) * i / n
            fp = f(p)
            if fp >= 0:
                a, b = prev_p, p
                for _ in range(60):
                    mid = (a + b) / 2
                    if f(mid) < 0:
                        a = mid
                    else:
                        b = mid
                return (a + b) / 2
            prev_p, prev_f = p, fp
        return hi

    def tip_half_angle(self) -> float:
        return self.half_angle(self.tip_radius)
